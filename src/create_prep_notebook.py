                "def expand_contractions(text: str) -> str:\n",
                "    pattern = re.compile(r'\\b(' + '|'.join(re.escape(k) for k in CONTRACTIONS_DICT.keys()) + r')\\b', re.IGNORECASE)\n",
                "    def replace(match):\n",
