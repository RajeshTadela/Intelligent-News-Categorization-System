                "### Mathematical & Theoretical Foundations\n",
                "\n",
                "#### 1. Bag of Words (BoW)\n",
                "Represents text by token occurrences while disregarding syntax and word order. Let vocabulary $V = \\{w_1, w_2, \\dots, w_{|V|}\\}$. A document $d$ is encoded as a count vector $\\mathbf{x} = [c(w_1, d), c(w_2, d), \\dots, c(w_{|V|}, d)]$.\n",
                "\n",
                "#### 2. Term Frequency (TF)\n",
                "Measures the relative frequency of term $t$ in document $d$:\n",
                "$$\\text{TF}(t, d) = \\frac{f_{t,d}}{\\sum_{t' \\in d} f_{t',d}} \\quad \\text{or sublinear scaling:} \\quad 1 + \\ln(f_{t,d}) \\quad (\\text{for } f_{t,d} > 0)$$\n",
                "\n",
                "#### 3. Inverse Document Frequency (IDF)\n",
                "Attenuates the weight of terms that occur very frequently across the entire corpus $D$:\n",
                "$$\\text{IDF}(t, D) = \\ln\\left(\\frac{1 + |D|}{1 + |\\{d \\in D : t \\in d\\}|}\\right) + 1$$\n",
                "\n",
                "#### 4. TF-IDF Score & L2 Normalization\n",
                "$$\\text{TF-IDF}(t, d, D) = \\text{TF}(t, d) \\times \\text{IDF}(t, D)$$\n",
                "Each document vector is subsequently projected onto the unit sphere via $L_2$ normalization:\n",
                "$$\\mathbf{v}_{\\text{norm}} = \\frac{\\mathbf{v}}{\\|\\mathbf{v}\\|_2} = \\frac{\\mathbf{v}}{\\sqrt{\\sum_i v_i^2}}$$\n",
                "\n",
                "#### 5. Unigrams vs Bigrams\n",
                "- **Unigram ($n=1$):** Single tokens (e.g., `interest`, `rates`).\n",
                "- **Bigram ($n=2$):** Adjacent word pairs (e.g., `interest rates`, `prime minister`, `operating system`), capturing critical compound phrases.\n",
                "\n",
                "#### 6. Sparse Matrices\n",
                "With vocabulary sizes of 10,000 to 20,000 terms, over 99% of entries per document are zero. We store features using Compressed Sparse Row (`scipy.sparse.csr_matrix`) format, ensuring minimal RAM consumption.\n",
                "\n",
                "---\n",
                "\n",
                "### Anti-Leakage Protocol\n",
                "- **Split before transformation:** Stratified 70% Train, 15% Validation, 15% Test.\n",
                "- **Fit strictly on Train:** The TF-IDF vectorizer vocabulary and IDF weights are computed exclusively from the 70% training partition.\n",
                "- **Validation for Tuning:** Hyperparameter optimization ($C$ penalty) is performed solely using the Validation set.\n",
                "- **Unbiased Test Evaluation:** Final metrics are computed on the untouched 15% Test split."
