                "### Core Conceptual Foundations\n",
                "\n",
                "#### 1. One-Hot Encoding\n",
                "In a one-hot representation, each word $w_i$ in a vocabulary of size $|V|$ is a binary vector of length $|V|$ with a single $1$ at index $i$ and $0$ elsewhere.\n",
                "- Example ($|V|=5$):  \n",
                "  `politics` = `[1, 0, 0, 0, 0]`  \n",
                "  `minister` = `[0, 1, 0, 0, 0]`  \n",
                "- **Critical Limitation:** All pairs of one-hot vectors are mutually orthogonal ($v_i \\cdot v_j = 0$). The cosine similarity between `politics` and `minister` is $0$, completely failing to capture semantic relatedness.\n",
                "\n",
                "#### 2. Sparse vs. Dense Representations\n",
                "| Feature | Sparse Representations (One-Hot / TF-IDF) | Dense Representations (Word2Vec Embeddings) |\n",
                "| :--- | :--- | :--- |\n",
                "| **Dimensionality** | High ($|V| \\approx 10,000 - 100,000$) | Low ($d \\approx 50 - 300$) |\n",
                "| **Sparsity** | >99% zeros | 100% continuous real numbers |\n",
                "| **Semantics** | None (orthogonal) | Encodes geometric semantic similarity |\n",
                "| **Memory** | Requires sparse matrix compression | Compact fixed-size float32 arrays |\n",
                "\n",
                "#### 3. What are Word Embeddings?\n",
                "A word embedding is a learned mapping function $f: w \\to \\mathbb{R}^d$ that maps discrete tokens into a continuous low-dimensional latent space where words appearing in similar linguistic contexts are positioned close to one another (Distributional Hypothesis: *\"You shall know a word by the company it keeps\"* — J.R. Firth, 1957).\n",
                "\n",
                "#### 4. Semantic Similarity (Cosine Similarity)\n",
                "Measures the angle between two word vectors $\\mathbf{u}$ and $\\mathbf{v}$:\n",
                "$$\\text{cosine_similarity}(\\mathbf{u}, \\mathbf{v}) = \\frac{\\mathbf{u} \\cdot \\mathbf{v}}{\\|\\mathbf{u}\\|_2 \\|\\mathbf{v}\\|_2} = \\frac{\\sum_{i=1}^d u_i v_i}{\\sqrt{\\sum_{i=1}^d u_i^2} \\sqrt{\\sum_{i=1}^d v_i^2}}$$\n",
                "\n",
                "#### 5. Word2Vec Architectures: CBOW vs. Skip-gram\n",
                "- **CBOW (Continuous Bag of Words, `sg=0`):**  \n",
                "  Predicts the target center word $w_t$ given its surrounding context window $\\{w_{t-k}, \\dots, w_{t+k}\\}$. Faster to train, slightly better for frequent words.\n",
                "- **Skip-gram (`sg=1`):**  \n",
                "  Predicts context words $\\{w_{t-k}, \\dots, w_{t+k}\\}$ given a target center word $w_t$. Slower, but excels at capturing semantic representations for rare and domain-specific words.\n",
                "\n",
                "#### 6. Embedding Dimensions ($d$)\n",
                "- **50-D:** Fast, lightweight, suitable for small corpora (<5,000 docs).\n",
                "- **100-D:** **Optimal balance** between representational capacity, generalization, and computational speed for ~10,000 news articles.\n",
                "- **200-D:** Higher capacity, but risks overfitting on small-to-medium corpora.\n",
                "\n",
                "#### 7. Out-Of-Vocabulary (OOV) Handling\n",
                "Words not present in the training vocabulary are assigned to a reserved `<OOV>` token at index `1` with a fixed, small random embedding vector.\n",
                "\n",
                "#### 8. Sequence Padding and Length\n",
                "Neural networks require uniform rectangular batch tensor shapes `(batch_size, max_seq_len)`.  \n",
                "- Sequences shorter than `max_seq_len` are padded with index `0` (`<PAD>`).  \n",
                "- Sequences longer than `max_seq_len` are post-truncated.\n",
                "\n",
