                "### Conceptual Foundations: Recurrent Neural Networks (RNN)\n",
                "\n",
                "#### 1. Sequential Data in NLP\n",
                "Natural language is inherently **sequential**. The meaning of a sentence does not depend merely on which words are present (as assumed by Bag-of-Words and TF-IDF), but on the **precise order** in which they appear, their grammatical structure, and temporal dependencies.\n",
                "- Example: *\"The athlete won the championship and entered politics\"* (Politics/Sports) vs. *\"The politician attended the championship game\"* (Sports/Politics). Order dictates the primary syntactic subject and topic.\n",
                "\n",
                "#### 2. What is a Recurrent Neural Network?\n",
                "Standard Feedforward Neural Networks process inputs independently under the assumption that all inputs are conditionally independent. A **Recurrent Neural Network (RNN)** introduces internal recurrent loops, allowing information to persist across consecutive time steps.\n",
                "\n",
                "#### 3. The Hidden State ($h_t$)\n",
                "The **hidden state** $h_t \\in \\mathbb{R}^d$ acts as the network's working memory at time step $t$. It combines the current input vector $x_t$ with the previous memory state $h_{t-1}$:\n",
                "$$h_t = \\tanh(W_{xh} x_t + W_{hh} h_{t-1} + b_h)$$\n",
                "Where:\n",
                "- $x_t \\in \\mathbb{R}^E$: Word embedding vector at time step $t$ ($E = 100$)\n",
                "- $W_{xh} \\in \\mathbb{R}^{H \\times E}$: Input-to-hidden weight matrix\n",
                "- $W_{hh} \\in \\mathbb{R}^{H \\times H}$: Hidden-to-hidden recurrent weight matrix\n",
                "- $b_h \\in \\mathbb{R}^H$: Bias vector\n",
                "- $\\tanh$: Non-linear activation bounding values between $[-1, 1]$\n",
                "\n",
                "The classification output at the final sequence step $T$ (or pooled over time) is computed as:\n",
                "$$\\hat{y} = \\text{softmax}(W_{hy} h_T + b_y)$$\n",
                "\n",
                "#### 4. Recurrent Connections & Unrolling Through Time\n",
                "We can conceptualize an RNN as a chain of identical copies of a neural cell, each passing a state vector to its successor:\n",
                "\n",
                "```\n",
                "Unrolled Architecture Across Time Steps (t = 1 to T):\n",
                "\n",
                "       y_hat (Output Class Probabilities: Softmax)\n",
                "         ^\n",
                "         | [W_hy]\n",
                "       [h_T] <--- [h_{T-1}] <--- ... <--- [h_2] <--- [h_1] <--- [h_0 = 0]\n",
                "         ^          ^                      ^          ^\n",
                "         | [W_xh]   | [W_xh]               | [W_xh]   | [W_xh]\n",
                "        x_T       x_{T-1}                 x_2        x_1\n",
                "```\n",
                "\n",
                "#### 5. Forward Propagation Step-by-Step\n",
                "1. Initialize initial hidden state $h_0 = \\mathbf{0}$.\n",
                "2. For each token $t = 1, 2, \\dots, T$:\n",
                "   - Look up dense embedding $x_t = \\mathbf{E}[w_t]$.\n",
                "   - Compute candidate activation: $a_t = W_{xh} x_t + W_{hh} h_{t-1} + b_h$.\n",
                "   - Compute updated hidden state: $h_t = \\tanh(a_t)$.\n",
                "3. Compute final logits $z = W_{hy} h_T + b_y$.\n",
                "4. Compute prediction probabilities $\\hat{y} = \\text{softmax}(z)$.\n",
                "\n",
                "#### 6. Backpropagation Through Time (BPTT)\n",
                "To optimize parameters $\\Theta = \\{W_{xh}, W_{hh}, W_{hy}, b_h, b_y\\}$, gradients of the loss $L$ are propagated backwards through every unrolled time step:\n",
                "$$\\frac{\\partial L}{\\partial W_{hh}} = \\sum_{t=1}^T \\frac{\\partial L}{\\partial h_t} \\frac{\\partial h_t}{\\partial W_{hh}}$$\n",
                "Where by the multivariate chain rule, the gradient with respect to hidden state $h_k$ ($k < t$) is:\n",
                "$$\\frac{\\partial h_t}{\\partial h_k} = \\prod_{j=k+1}^t \\frac{\\partial h_j}{\\partial h_{j-1}} = \\prod_{j=k+1}^t \\text{diag}(1 - h_j^2) W_{hh}^T$$\n",
                "\n",
                "#### 7. The Vanishing Gradient Problem\n",
                "Notice the continuous product matrix term $\\prod_{j=k+1}^t W_{hh}^T$:\n",
                "- Since $|1 - h_j^2| \\le 1$ for $\\tanh$, and if the largest eigenvalue of $W_{hh}$ satisfies $\\lambda_{\\max} < 1$, the gradient decays **exponentially fast** toward zero as the temporal distance $(t - k)$ increases.\n",
                "- Conversely, if $\\lambda_{\\max} > 1$, gradients explode (mitigated via gradient clipping).\n",
                "\n",
                "#### 8. Why Simple RNN Struggles with Long Sequences\n",
                "Because of vanishing gradients:\n",
                "- Early words in long articles (e.g. at step $t=1..20$) have virtually zero gradient signal by the time backpropagation reaches them from $t=150$.\n",
                "- The model develops a severe **recency bias**, overweighting words at the end of the text and forgetting critical context established at the beginning.\n",
                "- This limitation provides the exact theoretical and practical motivation for **Gated Architectures (LSTM / GRU)**, which introduce constant error carousels and additive cell state updates."
