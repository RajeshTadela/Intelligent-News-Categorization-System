                "def build_rnn_classifier(vocab_size, embedding_dim, max_len, embedding_matrix, trainable_embeddings=False, rnn_units=64):\n",
                "    \"\"\"\n",
                "    Builds a compiled Keras Simple RNN classifier.\n",
                "    \"\"\"\n",
                "    model = models.Sequential([\n",
                "        layers.Input(shape=(max_len,), name=\"sequence_input\"),\n",
                "        layers.Embedding(\n",
                "            input_dim=vocab_size,\n",
                "            output_dim=embedding_dim,\n",
                "            weights=[embedding_matrix],\n",
                "            trainable=trainable_embeddings,\n",
                "            name=\"word2vec_embedding\"\n",
                "        ),\n",
                "        layers.SimpleRNN(\n",
                "            units=rnn_units,\n",
                "            activation='tanh',\n",
                "            dropout=0.2,\n",
                "            return_sequences=False,\n",
                "            name=\"recurrent_layer\"\n",
                "        ),\n",
                "        layers.Dense(32, activation='relu', name=\"dense_projection\"),\n",
                "        layers.Dropout(0.3, name=\"regularization_dropout\"),\n",
                "        layers.Dense(5, activation='softmax', name=\"output_probabilities\")\n",
                "    ], name=f\"SimpleRNN_{'FineTuned' if trainable_embeddings else 'Frozen'}\")\n",
                "    \n",
                "    optimizer = keras.optimizers.Adam(learning_rate=1e-3)\n",
                "    model.compile(\n",
                "        optimizer=optimizer,\n",
                "        loss='sparse_categorical_crossentropy',\n",
                "        metrics=['accuracy']\n",
                "    )\n",
                "    return model\n",
